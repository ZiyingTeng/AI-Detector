"""AI Text Detector — Streamlit front end (F).

Run from the repo root:  streamlit run app.py
"""
import html
import os
import re

import pandas as pd
import streamlit as st

import gltr
from detectors import load_detectors, run

st.set_page_config(page_title="AI Text Detector", layout="wide")

DEMO_FILE = "P7_demo_texts.csv"   # from D: columns name,text
DEMO_LABELS = {
    "human": "Human-written",
    "chatgpt": "ChatGPT",
    "new_model": "Newer LLM (unseen generator)",
    "attacked": "Newer LLM, paraphrase-attacked",
}
FALLBACK_SAMPLES = {
    "ChatGPT-style (sample)": "Artificial intelligence has the potential to transform education by providing "
    "personalized learning experiences. However, it is important to consider the ethical implications, including "
    "privacy concerns and the risk of over-reliance on technology. Institutions should develop clear policies, "
    "train teachers to use these tools responsibly, and make sure that students continue to build independent "
    "thinking skills rather than relying on automated answers.",
}


@st.cache_data
def load_samples() -> dict:
    if os.path.exists(DEMO_FILE):
        try:
            df = pd.read_csv(DEMO_FILE, encoding="utf-8-sig")
            return {DEMO_LABELS.get(str(n), str(n)): str(t) for n, t in zip(df["name"], df["text"])}
        except Exception:
            pass
    return FALLBACK_SAMPLES


detectors = load_detectors()
samples = load_samples()

# ---------------- sidebar ----------------
with st.sidebar:
    st.header("Detectors")
    enabled = {}
    for key, d in detectors.items():
        label = f"{key} · {d['name']}" + ("  (mock)" if d["mock"] else "")
        enabled[key] = st.checkbox(label, value=True, key=f"use_{key}")
    threshold = st.slider("Decision threshold", 0.0, 1.0, 0.5, 0.05)
    st.divider()
    sample_name = st.selectbox("Example text", ["(type your own)"] + list(samples))
    mocks = {k: d for k, d in detectors.items() if d["mock"]}
    if mocks:
        with st.expander("Why are some detectors (mock)?"):
            for k, d in mocks.items():
                st.caption(f"**{k}**: {d['error']}")

# ---------------- main ----------------
st.title("AI Text Detector")
st.caption("Four detectors judge whether a passage was written by a human or generated by an AI.")
default_text = samples.get(sample_name, "")
text = st.text_area("Paste a passage (at least 40 words)", value=default_text, height=170, key=f"text_{sample_name}")
go = st.button("Detect", type="primary", disabled=not text.strip())

if go and text.strip():
    results = {}
    with st.spinner("Running detectors… (the LLM judge can take a few seconds)"):
        for key, d in detectors.items():
            if enabled[key]:
                results[key] = run(key, d, text)

    usable = {k: r for k, r in results.items() if r and r["usable"]}

    # ---- overall verdict ----
    if usable:
        mean_p = sum(r["prob_ai"] for r in usable.values()) / len(usable)
        n_ai = sum(r["prob_ai"] >= threshold for r in usable.values())
        if abs(mean_p - threshold) < 0.1:
            verdict = "Uncertain"
        elif mean_p >= threshold:
            verdict = "Likely AI-generated"
        else:
            verdict = "Likely human-written"
        c1, c2, c3 = st.columns(3)
        c1.metric("Verdict", verdict)
        c2.metric("Mean AI score", f"{mean_p:.2f}")
        c3.metric("Detectors flagging AI", f"{n_ai} / {len(usable)}")
    else:
        st.warning("No detector returned a usable score for this text.")
    st.caption("Detector outputs are probabilistic and should not be used as the sole evidence of misconduct.")

    # ---- per-detector results ----
    st.subheader("Detectors")
    for key, r in results.items():
        d = detectors[key]
        cols = st.columns([2, 5, 1])
        cols[0].markdown(f"**{key} · {d['name']}**" + (" *(mock)*" if d["mock"] else ""))
        if r is None:
            cols[1].warning("Unavailable (the call failed — check the model download or API key)")
            continue
        cols[1].progress(r["prob_ai"])
        cols[2].markdown(f"`{r['prob_ai']:.2f}`")
        details = []
        if r["perplexity"] is not None:
            details.append(f"Perplexity: {float(r['perplexity']):.1f}")
        details += r["notes"]
        if details:
            st.caption(" · ".join(details))
        if r["reason"]:
            st.caption(f"LLM reasoning: {r['reason']}")

    # ---- GLTR colouring ----
    st.subheader("Token ranks under GPT-2 (GLTR)")
    st.caption("AI text tends to pick the words GPT-2 expects (mostly green); human text uses more surprising words.")
    pairs, gltr_mock = gltr.token_ranks(text)
    if gltr_mock:
        st.caption("GPT-2 is not installed, so the colours below are random. Install torch and transformers.")
    left, right = st.columns([3, 1])
    left.markdown(gltr.render(pairs), unsafe_allow_html=True)
    left.markdown(gltr.legend(), unsafe_allow_html=True)
    right.bar_chart(pd.Series(gltr.fractions(pairs), name="share"), height=220)

    # ---- sentence level ----
    with st.expander("Sentence-level view"):
        sents = None
        c = results.get("C")
        if c and c["sentences"]:
            sents = [(s["text"], float(s["prob_ai"])) for s in c["sentences"]]
            st.caption("Each sentence scored by C · Fine-tuned RoBERTa. Short sentences are less reliable.")
        else:
            pick = next((k for k in ["C", "B"] if usable.get(k)), None)
            if pick:
                st.caption(f"Each sentence scored by {pick} · {detectors[pick]['name']}. Short sentences are less reliable.")
                sents = []
                for s in [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]:
                    r = run(pick, detectors[pick], s)
                    sents.append((s, r["prob_ai"] if r else 0.0))
        if sents:
            parts = [
                f'<span style="background:rgba(244,67,54,{0.06 + 0.5 * p:.2f});border-radius:3px;'
                f'padding:1px 2px" title="AI score {p:.2f}">{html.escape(s)}</span>'
                for s, p in sents
            ]
            st.markdown('<div style="line-height:2">' + " ".join(parts) + "</div>", unsafe_allow_html=True)
            st.caption("Darker red = higher AI score.")
        else:
            st.info("Enable C or B to see sentence-level scores.")
